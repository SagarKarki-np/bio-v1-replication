    parser.add_argument(
        "--output-dir",
        type=str,
        default=str(DEFAULT_OUTPUT_DIR),
        help="Directory for OSI results and figures"
    )

    parser.add_argument(
        "--show",
        action="store_true",
        help="Display figures interactively"
    )

    args = parser.parse_args()

    analyze_osi_learning(
        input_path=args.input,
        output_dir=args.output_dir,
        show=args.show
    )
